import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (name) => fs.readFileSync(path.join(root, name), "utf8");
const commands = [
  ...read("apps/desktop/src-tauri/desktop_commands.rs").matchAll(/^\s+([a-z_]+),?\s*$/gm),
]
  .map((match) => match[1])
  .sort();
const eventChannels = [
  ...read("apps/desktop/src-tauri/src/jobs.rs").matchAll(
    /pub const CHANNEL_[A-Z_]+: &str = "([^"]+)"/g,
  ),
]
  .map((match) => match[1])
  .sort();
const config = JSON.parse(read("apps/desktop/src-tauri/tauri.conf.json"));
const metadata = JSON.parse(read("apps/desktop/src-tauri/dezoomify.json"));
const { codecs } = JSON.parse(read("generated/output-codecs.json"));
metadata.outputFormats = codecs.map((codec) => codec.format);
metadata.encoders = codecs
  .filter((codec) => codec.layout !== "directory")
  .map((codec) => codec.format);
metadata.commands = commands;
metadata.eventChannels = eventChannels;
metadata.updater = {
  allowlist: config.plugins.updater.endpoints,
  channel: "latest",
  enabled: config.plugins.updater.endpoints.length > 0 && Boolean(config.plugins.updater.pubkey),
  httpsOnly: true,
  requiresUserConfirm: true,
};

const capabilities = {
  $schema: "../gen/schemas/desktop-schema.json",
  description: "Desktop permissions generated by scripts/generate-desktop-capabilities.mjs.",
  identifier: "generated",
  permissions: [
    "core:default",
    "dialog:allow-open",
    "opener:allow-open-url",
    ...commands.map((name) => `dezoomify:allow-${name.replaceAll("_", "-")}`),
  ],
  windows: ["main"],
  "x-dezoomify": metadata,
};
const artifacts = {
  "apps/desktop/src-tauri/dezoomify.json": metadata,
  "apps/desktop/src-tauri/capabilities/generated.json": capabilities,
  "generated/desktop-capabilities.json": {
    app: "desktop",
    bundle: { identifier: config.identifier },
    ...metadata,
    generator: "scripts/generate-desktop-capabilities.mjs",
  },
};
for (const [name, value] of Object.entries(artifacts)) {
  const content = `${JSON.stringify(value, null, 2)}\n`;
  if (process.argv.includes("--check")) {
    if (read(name) !== content)
      throw new Error(
        `Desktop capabilities differ: ${name}; run node scripts/generate-desktop-capabilities.mjs`,
      );
  } else fs.writeFileSync(path.join(root, name), content);
}
