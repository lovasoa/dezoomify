//! Generated WASM ABI declaration checks.
//!
//! Rust DTOs are authoritative. `wasm-bindgen` and `tsify` produce the only
//! TypeScript declaration consumed by browser products.

use std::path::PathBuf;

const TRACKED_DECLARATION: &str = "packages/wasm-bindings/src/generated.d.ts";
const CODEC_MANIFEST: &str = "generated/output-codecs.json";
const CODEC_DECLARATION: &str = "packages/wasm-bindings/src/codecs.d.mts";
const CODEC_EXPORT: &str = "// Generated by cargo xtask bindings generate from model.rs.\nimport type { OutputCodec } from \"./generated.d.ts\";\nexport const outputCodecs: readonly OutputCodec[];\n";

fn codec_manifest() -> Result<String, String> {
    dezoomify::model::OUTPUT_CODECS
        .iter()
        .map(serde_json::to_string)
        .collect::<Result<Vec<_>, _>>()
        .map(|rows| format!("[\n  {}\n]\n", rows.join(",\n  ")))
        .map_err(|error| error.to_string())
}

pub(crate) fn check_codec_manifest() -> Result<(), String> {
    for (path, expected) in [
        (CODEC_MANIFEST, codec_manifest()?),
        (CODEC_DECLARATION, CODEC_EXPORT.to_string()),
    ] {
        let actual = std::fs::read_to_string(super::repo_root().join(path))
            .map_err(|error| error.to_string())?;
        if actual != expected {
            return Err(format!(
                "{path} is stale; run cargo xtask bindings generate"
            ));
        }
    }
    Ok(())
}

pub fn run(args: &[String]) -> Result<(), String> {
    match args.first().map(String::as_str) {
        Some("generate") => generate(&args[1..]),
        Some("check") => check(&args[1..]),
        Some(other) => Err(format!(
            "unknown bindings subcommand '{other}' (only 'generate|check')"
        )),
        None => Err("usage: cargo xtask bindings <generate|check>".to_string()),
    }
}

fn generate(args: &[String]) -> Result<(), String> {
    if !args.is_empty() {
        return Err("usage: cargo xtask bindings generate (no options)".to_string());
    }
    let generated = emit_declaration()?;
    let tracked = super::repo_root().join(TRACKED_DECLARATION);
    std::fs::copy(&generated, &tracked).map_err(|e| {
        format!(
            "copy generated binding {} to {}: {e}",
            generated.display(),
            tracked.display()
        )
    })?;
    println!("bindings generate: wrote {}", tracked.display());
    std::fs::write(super::repo_root().join(CODEC_MANIFEST), codec_manifest()?)
        .and_then(|()| std::fs::write(super::repo_root().join(CODEC_DECLARATION), CODEC_EXPORT))
        .map_err(|error| error.to_string())?;
    let status = std::process::Command::new("node")
        .arg("scripts/generate-desktop-capabilities.mjs")
        .current_dir(super::repo_root())
        .status()
        .map_err(|error| error.to_string())?;
    if !status.success() {
        return Err("desktop capability generation failed".to_string());
    }
    Ok(())
}

fn emit_declaration() -> Result<PathBuf, String> {
    let input = super::wasm::build_wasm_artifact(true)?;
    let output =
        std::env::temp_dir().join(format!("dezoomify-wasm-bindings-{}", std::process::id()));
    if output.exists() {
        std::fs::remove_dir_all(&output)
            .map_err(|e| format!("clear temporary binding directory: {e}"))?;
    }
    std::fs::create_dir_all(&output)
        .map_err(|e| format!("create temporary binding directory: {e}"))?;
    super::wasm::run_wasm_bindgen(
        &input,
        &super::wasm::Bindgen {
            target: "web",
            out_dir: &output,
            out_name: "dezoomify-wasm",
            typescript: true,
        },
    )?;
    Ok(output.join("dezoomify-wasm.d.ts"))
}

fn check(args: &[String]) -> Result<(), String> {
    super::reject_unknown_args("bindings check", args)?;
    check_codec_manifest()?;
    super::command::cargo_test(&["-p", "dezoomify"])?;
    typecheck_binding()?;
    wasm_portability_check()?;
    println!("bindings check: ok");
    Ok(())
}

pub fn test_bindings() -> Result<(), String> {
    check_codec_manifest()?;
    super::command::cargo_test(&["-p", "dezoomify"])?;
    typecheck_binding()?;
    wasm_portability_check()
}

pub(crate) fn wasm_portability_check() -> Result<(), String> {
    super::command::cargo(&[
        "check",
        "--quiet",
        "-p",
        "dezoomify",
        "--target",
        "wasm32-unknown-unknown",
        "--no-default-features",
    ])
}

fn typecheck_binding() -> Result<(), String> {
    let status = super::desktop::pnpm_command()?
        .args(["--filter", "@dezoomify/wasm-bindings", "typecheck"])
        .current_dir(super::repo_root())
        .status()
        .map_err(|e| format!("run generated binding typecheck: {e}"))?;
    if status.success() {
        Ok(())
    } else {
        Err("generated binding TypeScript compilation failed".to_string())
    }
}
